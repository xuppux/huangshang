#ifndef _BLE_AI_H
#define _BLE_AI_H

/*
 * ble_ai.h —— AI 助手的蓝牙数据通道（手表 <-> 电脑/手机）
 *
 * 这块板没有 WiFi，要联网只能借着手机/电脑的网。这条通道就是「借」的方式：
 * 手表把文字发出去、收回来，联网和调大模型都交给对端做。
 *
 * 实现见 ble_ai.c（那里有完整的格式说明和一个「编译通过但等于没开」的坑）。
 */

/* 在 BLE 工作线程里调一次（协议栈就绪之后）。
 * ⚠ 不要在 BLE 事件回调里调 —— 注册 GATT 服务会阻塞协议栈。
 * 幂等，重复调无副作用。 */
void ble_ai_serial_init(void);

/* 往对端发一段文字。
 * 返回值：>= 0 表示发出的字节数；< 0 表示失败（-1 通道未就绪，-3 内存不足等）。
 * 内部自动分包，文本多长都行（服务自己切包）。 */
int ble_ai_send(const char *text);

/* 通道是否就绪（对端已连上、服务已打开）。1 = 可以发。 */
int ble_ai_is_up(void);

/* 回声开关（默认开）。
 *
 * 开的时候，手表收到什么都原样回一句 "[watch] got N bytes: ..." ——
 * 这是**回答器的占位实现**，让电脑端一个脚本就能验证双向通道。
 *
 * 阶段二手表自己会回答之后，把它关掉（或者直接删掉回声那段，
 * 换成把问题转给电脑）。对应串口命令 ai_echo 0|1。 */
void ble_ai_set_echo(int on);

#endif /* _BLE_AI_H */
